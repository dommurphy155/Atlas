@dataclass
class ServiceConfig:
    """Service configuration."""
    name: str = "atlas-proxy"
    display_name: str = "Atlas Proxy"
    description: str = "Atlas Multi-Provider Proxy (OpenRouter/NVIDIA)"
    working_dir: str = ""
    python_path: str = ""
    module: str = "proxy.main"
    user: str = ""
    env: dict[str, str] = None

    def __post_init__(self):
        if self.env is None:
            self.env = {}


