def install_systemd_service(config: ServiceConfig, platform_info: PlatformInfo) -> bool:
    """Install systemd service on Linux."""
    if not platform_info.is_linux:
        return False

    # Check systemctl
    if not shutil.which("systemctl"):
        console.error("systemctl not found")
        return False

    # Render template
    env_vars = "\n".join(f"Environment={k}={v}" for k, v in config.env.items())
    unit = SYSTEMD_TEMPLATE.format(
        description=config.description,
        user=config.user or os.getenv("SUDO_USER") or os.getenv("USER") or "root",
        working_dir=config.working_dir,
        home=str(Path.home()),
        venv_bin=str(Path(config.python_path).parent),
        python_path=config.python_path,
        module=config.module,
        env_vars=env_vars,
    )

    # Write unit file
    unit_path = Path("/etc/systemd/system") / f"{config.name}.service"
    try:
        if os.geteuid() == 0:
            write_file(unit_path, unit)
        else:
            # Use sudo tee
            subprocess.run(
                ["sudo", "tee", str(unit_path)],
                input=unit.encode(),
                check=True,
                stdout=subprocess.DEVNULL,
            )
    except Exception as e:
        console.error(f"Failed to write systemd unit: {e}")
        return False

    # Reload and enable
    try:
        subprocess.run(["systemctl", "daemon-reload"], check=True)
        subprocess.run(["systemctl", "enable", "--now", config.name], check=True)
        console.success(f"Installed and started systemd service: {config.name}")
        return True
    except subprocess.CalledProcessError as e:
        console.error(f"Failed to enable/start service: {e}")
        return False


def install_launchd_service(config: ServiceConfig, platform_info: PlatformInfo) -> bool:
    """Install launchd agent on macOS."""
    if not platform_info.is_macos:
        return False

    label = config.name.replace("-", ".")
    plist = LAUNCHD_TEMPLATE.format(
        label=label,
        python_path=config.python_path,
        module=config.module,
        working_dir=config.working_dir,
        home=str(Path.home()),
        venv_bin=str(Path(config.python_path).parent),
    )

    plist_dir = Path.home() / "Library" / "LaunchAgents"
    ensure_dir(plist_dir)
    plist_path = plist_dir / f"{label}.plist"

    try:
        write_file(plist_path, plist)
        # Unload if exists
        subprocess.run(["launchctl", "unload", str(plist_path)], check=False)
        # Load new
        subprocess.run(["launchctl", "load", "-w", str(plist_path)], check=True)
        subprocess.run(["launchctl", "start", label], check=True)
        console.success(f"Installed and started launchd agent: {label}")
        return True
    except Exception as e:
        console.error(f"Failed to install launchd agent: {e}")
        return False


def install_windows_service(config: ServiceConfig, platform_info: PlatformInfo) -> bool:
    """Install Windows Service."""
    if not platform_info.is_windows:
        return False

    try:
        import win32serviceutil
    except ImportError:
        console.info("Installing pywin32...")
        subprocess.run([config.python_path, "-m", "pip", "install", "pywin32"], check=True)
        import win32serviceutil

    # Write service module
    service_dir = Path(config.working_dir) / "setup"
    ensure_dir(service_dir)
    service_module = service_dir / "atlas_windows_service.py"

    env_setup = "        env[\"HOME\"] = os.path.expanduser(\"~\")\n"
    env_dict = ", ".join(f'"{k}": "{v}"' for k, v in config.env.items())

    service_code = WINDOWS_SERVICE_TEMPLATE.format(
        name=config.name,
        display_name=config.display_name,
        description=config.description,
        python_path=config.python_path,
        module=config.module,
        working_dir=config.working_dir,
        env_setup=env_setup,
        env_dict=env_dict,
    )

    write_file(service_module, service_code)

    # Install service
    try:
        subprocess.run([config.python_path, str(service_module), "--install"], check=True)
        subprocess.run([config.python_path, str(service_module), "--start"], check=True)
        console.success(f"Installed and started Windows Service: {config.name}")
        return True
    except Exception as e:
        console.error(f"Failed to install Windows Service: {e}")
        return False


def install_service(config: ServiceConfig, platform_info: PlatformInfo) -> bool:
    """Install service for current platform."""
    if platform_info.is_linux:
        return install_systemd_service(config, platform_info)
    elif platform_info.is_macos:
        return install_launchd_service(config, platform_info)
    elif platform_info.is_windows:
        return install_windows_service(config, platform_info)
    else:
        console.warning(f"No service installer for {platform_info.system}")
        return False


def uninstall_service(name: str, platform_info: PlatformInfo) -> bool:
    """Uninstall service."""
    if platform_info.is_linux:
        try:
            subprocess.run(["systemctl", "disable", "--now", name], check=False)
            unit_path = Path(f"/etc/systemd/system/{name}.service")
            if unit_path.exists():
                unit_path.unlink()
            subprocess.run(["systemctl", "daemon-reload"], check=False)
            console.success(f"Removed systemd service: {name}")
            return True
        except Exception as e:
            console.error(f"Failed to remove systemd service: {e}")
            return False

    elif platform_info.is_macos:
        label = name.replace("-", ".")
        try:
            subprocess.run(["launchctl", "unload", f"~/Library/LaunchAgents/{label}.plist"], check=False)
            plist_path = Path.home() / "Library" / "LaunchAgents" / f"{label}.plist"
            plist_path.unlink(missing_ok=True)
            console.success(f"Removed launchd agent: {label}")
            return True
        except Exception as e:
            console.error(f"Failed to remove launchd agent: {e}")
            return False

    elif platform_info.is_windows:
        try:
            service_module = Path(config.working_dir) / "setup" / "atlas_windows_service.py"
            if service_module.exists():
                subprocess.run([config.python_path, str(service_module), "--remove"], check=False)
            console.success(f"Removed Windows Service: {name}")
            return True
        except Exception as e:
            console.error(f"Failed to remove Windows Service: {e}")
            return False

    return False