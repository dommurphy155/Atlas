def get_env_path(platform_info: PlatformInfo) -> Path:
    """Get .env file path."""
    return platform_info.project_dir / ".env"


def load_env(path: Path) -> dict[str, str]:
    """Load .env file into dict."""
    env = {}
    content = read_file(path)
    if content:
        for line in content.splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            env[key.strip()] = value.strip()
    return env


def write_env(path: Path, config: EnvConfig) -> bool:
    """Write .env file from config."""
    lines = ["# Atlas Proxy Configuration", "# Generated by atlas-setup — edit freely"]
    for key, value in config.to_env_dict().items():
        lines.append(f"{key}={value}")
    return write_file(path, "\n".join(lines) + "\n")


def ensure_env_file(platform_info: PlatformInfo, config: Optional[EnvConfig] = None) -> EnvConfig:
    """Ensure .env exists, create from template if not."""
    env_path = get_env_path(platform_info)
    if env_path.exists():
        console.info(f".env exists: {env_path}")
        existing = load_env(env_path)
        if config is None:
            config = EnvConfig()
        # Update config from existing env
        for key, value in existing.items():
            attr = key.lower()
            if hasattr(config, attr):
                # Type conversion
                current = getattr(config, attr)
                if isinstance(current, bool):
                    value = value.lower() in ("1", "true", "yes", "on")
                elif isinstance(current, int):
                    value = int(value)
                setattr(config, attr, value)
        return config

    config = config or EnvConfig()
    # Set default keys file paths
    data_dir = platform_info.project_dir / "data"
    config.nvidia_keys_file = str(data_dir / "keys.txt")
    config.openrouter_keys_file = str(data_dir / "openroute_keys.txt")
    config.system_prompt_override_file = str(platform_info.project_dir / "data" / "system_prompt_override.txt")

    write_env(env_path, config)
    console.success(f"Created .env: {env_path}")

    # Install shell exports
    install_shell_env(platform_info, config)
    return config


def install_shell_env(platform_info: PlatformInfo, config: EnvConfig) -> bool:
    """Install ANTHROPIC_* exports into shell rc files."""
    if platform_info.is_windows:
        return install_shell_env_windows(config)

    rc_files = []
    shell = platform_info.shell
    if shell == "zsh":
        rc_files = [platform_info.home / ".zshrc", platform_info.home / ".bashrc"]
    elif shell == "fish":
        rc_files = [platform_info.home / ".config" / "fish" / "config.fish"]
    else:
        rc_files = [platform_info.home / ".bashrc", platform_info.home / ".zshrc"]

    marker = "# --- Atlas Proxy (ANTHROPIC_*) ---"
    exports = [
        f'export ANTHROPIC_BASE_URL="http://127.0.0.1:8788"',
        f'export ANTHROPIC_API_KEY="atlas"',
        f'unset ANTHROPIC_AUTH_TOKEN 2>/dev/null || true',
    ]

    success = True
    for rc in rc_files:
        if rc.exists():
            content = read_file(rc) or ""
            if marker in content:
                console.info(f"Already configured in {rc.name}")
                continue
            if append_to_file(rc, [marker] + exports + ["# --- end Atlas ---"]):
                console.success(f"Added ANTHROPIC_* exports to {rc.name}")
            else:
                success = False
        else:
            console.debug(f"Shell rc not found: {rc}")

    return success


def install_shell_env_windows(config: EnvConfig) -> bool:
    """Install env vars on Windows via setx."""
    try:
        for name, value in (
            ("ANTHROPIC_BASE_URL", "http://127.0.0.1:8788"),
            ("ANTHROPIC_API_KEY", "atlas"),
        ):
            subprocess.run(["setx", name, value], check=False,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            console.success(f"setx {name} (persists for new shells)")
        # Clear AUTH_TOKEN if present
        subprocess.run(["reg", "delete", "HKCU\\Environment", "/v", "ANTHROPIC_AUTH_TOKEN", "/f"],
                       check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        return True
    except Exception as e:
        console.error(f"Failed to set Windows env: {e}")
        return False