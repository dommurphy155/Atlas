console = get_console()


@dataclass
class EnvConfig:
    """Atlas environment configuration."""
    # Proxy
    proxy_host: str = "127.0.0.1"
    proxy_port: int = 8788

    # Provider selection
    provider: str = "openrouter"  # "nvidia" | "openrouter"

    # NVIDIA
    nvidia_base_url: str = "https://integrate.api.nvidia.com/v1/chat/completions"
    nvidia_model: str = "nvidia/nemotron-3-ultra-550b-a55b"
    nvidia_keys_file: str = ""

    # OpenRouter
    openrouter_base_url: str = "https://openrouter.ai/api/v1"
    openrouter_model: str = "nemotron-3-ultra-550b-a55b:free"
    openrouter_keys_file: str = ""

    # Proxy tuning
    proxy_reload_seconds: int = 5
    proxy_cooldown_seconds: int = 45
    proxy_suspend_seconds: int = 600
    proxy_max_errors: int = 8
    proxy_debug: bool = False

    # System prompt override
    system_prompt_override_enabled: bool = True
    system_prompt_override_file: str = ""

    # Computed
    anthropic_base_url: str = field(init=False)
    anthropic_api_key: str = field(init=False)

    def __post_init__(self):
        self.anthropic_base_url = f"http://{self.proxy_host}:{self.proxy_port}"
        self.anthropic_api_key = "atlas"

    def to_env_dict(self) -> dict[str, str]:
        """Convert to environment variable dict."""
        d = {
            "ATLAS_PROXY_HOST": self.proxy_host,
            "ATLAS_PROXY_PORT": str(self.proxy_port),
            "ATLAS_PROVIDER": self.provider,
            "ATLAS_NVIDIA_BASE_URL": self.nvidia_base_url,
            "ATLAS_NVIDIA_MODEL": self.nvidia_model,
            "ATLAS_OPENROUTER_BASE_URL": self.openrouter_base_url,
            "ATLAS_OPENROUTER_MODEL": self.openrouter_model,
            "ATLAS_PROXY_RELOAD_SECONDS": str(self.proxy_reload_seconds),
            "ATLAS_PROXY_COOLDOWN_SECONDS": str(self.proxy_cooldown_seconds),
            "ATLAS_PROXY_SUSPEND_SECONDS": str(self.proxy_suspend_seconds),
            "ATLAS_PROXY_MAX_ERRORS": str(self.proxy_max_errors),
            "ATLAS_PROXY_DEBUG": "1" if self.proxy_debug else "0",
            "SYSTEM_PROMPT_OVERRIDE_ENABLED": "1" if self.system_prompt_override_enabled else "0",
        }
        if self.nvidia_keys_file:
            d["ATLAS_NVIDIA_KEYS_FILE"] = self.nvidia_keys_file
        if self.openrouter_keys_file:
            d["ATLAS_OPENROUTER_KEYS_FILE"] = self.openrouter_keys_file
        if self.system_prompt_override_file:
            d["SYSTEM_PROMPT_OVERRIDE_FILE"] = self.system_prompt_override_file
        return d


